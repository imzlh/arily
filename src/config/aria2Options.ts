/** Flattened lookup: option key -> definition (first group wins). */
export const ARIA2_OPTION_MAP: ReadonlyMap<string, Aria2OptionDef> = new Map(
  ARIA2_OPTION_GROUPS.flatMap((group) => group.options).map((def) => [def.key, def]),
)

/** Total number of options across all groups. */
export const ARIA2_OPTION_COUNT = ARIA2_OPTION_GROUPS.reduce((sum, group) => sum + group.options.length, 0)
