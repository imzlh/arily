/**
 * Schema of every aria2 option exposed on the settings page, ported from
 * AriaNg (`aria2AllOptions` + `aria2GlobalAvailableOptions`) with Chinese
 * labels and descriptions from AriaNg's zh_Hans language pack.
 *
 * The groups below mirror aria2's option categories in AriaNg's order; each
 * entry carries the metadata needed to render and validate a single field:
 * type, unit suffix, enum values, readonly flag (launch-time options that
 * aria2's changeGlobalOption rejects), defaults and min/max bounds.
 */

export type Aria2OptionType = 'string' | 'integer' | 'float' | 'boolean' | 'option' | 'text'

export interface Aria2OptionDef {
  key: string
  label: string
  description?: string
  type: Aria2OptionType
  suffix?: 'Bytes' | 'Milliseconds' | 'Seconds' | 'Minutes' | 'Hours'
  options?: { value: string; label: string }[]
  readonly?: boolean
  defaultValue?: string
  min?: number
  max?: number
  since?: string
  /** Separator used to join/split multi-value options of type 'text'. */
  separator?: string
}

export interface Aria2OptionGroup {
  id: string
  label: string
  icon?: string
  options: Aria2OptionDef[]
}

